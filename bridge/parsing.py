"""
Detects the series title, season and episode number in a video file name or caption.

    "Harem Wars - System vs. Queen - S01E03.ts" -> ("Harem Wars - System vs. Queen", 1, 3)
    "Harem.Wars.S02E10.1080p.WEB-DL.mkv"        -> ("Harem Wars", 2, 10)
    "Mon Drama - Épisode 3"                     -> ("Mon Drama", None, 3)
    "مسلسل الحب الحلقة ٧"                       -> ("مسلسل الحب", None, 7)
"""
import re
from typing import NamedTuple, Optional

VIDEO_EXTENSIONS = {".mp4", ".ts", ".mkv", ".mov", ".m4v", ".avi", ".webm", ".m2ts", ".mts", ".flv", ".wmv", ".3gp"}

_ARABIC_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")
_EXT_RE = re.compile(r"\.(" + "|".join(e[1:] for e in sorted(VIDEO_EXTENSIONS)) + r")$", re.IGNORECASE)

# Ordered from the most to the least specific.
_PATTERNS = [
    re.compile(r"\bS(?P<season>\d{1,2})\s*[._-]?\s*E(?P<episode>\d{1,4})\b", re.IGNORECASE),
    re.compile(r"\b(?P<season>\d{1,2})x(?P<episode>\d{1,4})\b", re.IGNORECASE),
    re.compile(r"\b(?:saison|season|temporada|sezon)\s*(?P<season>\d{1,2})\W{0,3}(?:[eé]pisode|episodio|ep|bölüm)\.?\s*(?P<episode>\d{1,4})\b", re.IGNORECASE),
    re.compile(r"(?:\bep(?:isode|isodio)?|\bé?pisode|\bépi?|\bpart(?:ie)?|\bfolge|\bbölüm|الحلقة|حلقة|\bح)\s*[.:#№-]?\s*(?P<episode>\d{1,4})", re.IGNORECASE),
    re.compile(r"#\s*(?P<episode>\d{1,4})\b"),
    re.compile(r"\b(?P<episode>\d{1,4})\s*/\s*\d{1,4}\b"),
    re.compile(r"\bE(?P<episode>\d{1,4})\b", re.IGNORECASE),
]
# A bare trailing number ("My Drama 12") only counts for file names.
_TRAILING_NUMBER = re.compile(r"[\s_.-]+(?P<episode>\d{1,3})$")

_RELEASE_TAGS = re.compile(
    r"\b(2160p|1080p|720p|480p|360p|4k|uhd|hdr|bluray|bdrip|brrip|web-?dl|webrip|web|hdtv|dvdrip|"
    r"x264|x265|hevc|h\.?264|h\.?265|avc|10bit|aac|ac3|dts|multi|vostfr|vf|truefrench|subfrench)\b",
    re.IGNORECASE,
)
_HASHTAG = re.compile(r"#([^\s#]+)")
# Names generated by phones/Telegram carry no series information.
_GENERIC_NAME = re.compile(r"^(?:video|vid|img|mov|pxl|telegram|file|document)[\s_-]*\d{4}[-_]?\d{2}[-_]?\d{2}", re.IGNORECASE)
_LEADING_TAGS = re.compile(r"^(?:\s*[\[(][^\])]{1,40}[\])])+")
_SEPARATORS = " \t-–—|:•·,._()[]{}"


class ParsedName(NamedTuple):
    title: Optional[str]
    season: Optional[int]
    episode: Optional[int]


def _clean_title(text: str) -> Optional[str]:
    text = _HASHTAG.sub(" ", text)
    text = re.sub(r"https?://\S+|t\.me/\S+|@\w+", " ", text)
    text = _RELEASE_TAGS.sub(" ", text)
    text = re.sub(r"[\[(]\s*[\])]", " ", text)
    text = re.sub(r"\s+", " ", text).strip(_SEPARATORS + " ")
    # Drop a dangling separator left behind ("Title -", "Title |")
    text = re.sub(r"\s*[-–—|:]+$", "", text).strip()
    return text if len(text) >= 2 else None


def parse_video_name(raw: str, is_filename: bool = False) -> ParsedName:
    """Returns the series title, season and episode found in a file name or caption."""
    text = (raw or "").translate(_ARABIC_DIGITS).strip()
    if not text:
        return ParsedName(None, None, None)

    if is_filename:
        text = _EXT_RE.sub("", text)
        if _GENERIC_NAME.match(text):
            return ParsedName(None, None, None)
        text = _LEADING_TAGS.sub("", text).strip()
        if " " not in text:
            # Scene-style names: Harem.Wars.S01E03 / Harem_Wars_S01E03
            text = re.sub(r"[._]+", " ", text)

    season = episode = None
    for pattern in _PATTERNS:
        match = pattern.search(text)
        if match:
            groups = match.groupdict()
            season = int(groups["season"]) if groups.get("season") else None
            episode = int(groups["episode"])
            text = text[:match.start()] + " " + text[match.end():]
            break
    if episode is None and is_filename:
        match = _TRAILING_NUMBER.search(text)
        if match:
            episode = int(match.group("episode"))
            text = text[:match.start()]

    title = None
    for line in (ln.strip() for ln in text.splitlines()):
        if line:
            title = _clean_title(line)
            if title:
                break
    if title is None:
        tags = [t for t in _HASHTAG.findall(raw or "") if not t.isdigit()]
        if tags:
            title = tags[0].replace("_", " ").strip()
    if title and len(title) > 200:
        title = title[:200].rstrip()
    return ParsedName(title, season, episode)


def series_title_with_season(title: str, season: Optional[int]) -> str:
    """Season 2+ becomes its own series: 'Title - S2'."""
    return f"{title} - S{season}" if season and season > 1 else title
